# ============================================================
# TANGLE INVESTIGATION REPORT
# ============================================================

import pandas as pd


# ============================================================
# CONFIGURATION
# ============================================================

RESULTS_FILE = "data/agent_results.csv"


# ============================================================
# LOAD RESULTS
# ============================================================

def load_results():
    """
    Load the results generated by the
    TANGLE investigation pipeline.
    """

    try:
        df = pd.read_csv(RESULTS_FILE)

        if df.empty:
            print("No investigation results found.")
            return None

        return df

    except FileNotFoundError:
        print(
            f"ERROR: Results file not found: {RESULTS_FILE}"
        )
        return None

    except Exception as error:
        print(
            f"ERROR: Could not load results: {error}"
        )
        return None


# ============================================================
# SUMMARY
# ============================================================

def print_summary(df):
    """
    Print high-level investigation statistics.
    """

    total_cases = len(df)

    reconciled = len(
        df[df["decision"] == "RECONCILE"]
    )

    investigate = len(
        df[df["decision"] == "INVESTIGATE"]
    )

    escalated = len(
        df[df["decision"] == "ESCALATE"]
    )

    high_confidence = len(
        df[df["confidence"] >= 0.90]
    )

    average_confidence = df["confidence"].mean()

    print()
    print("=" * 70)
    print("                 TANGLE INVESTIGATION REPORT")
    print("=" * 70)

    print()
    print(f"Total Cases              : {total_cases}")
    print(f"Reconciled               : {reconciled}")
    print(f"Requires Investigation   : {investigate}")
    print(f"Escalated                : {escalated}")

    print()
    print(
        f"High Confidence (>=90%) : {high_confidence}"
    )

    print(
        f"Average Confidence      : "
        f"{average_confidence:.2%}"
    )


# ============================================================
# DECISION BREAKDOWN
# ============================================================

def print_decision_breakdown(df):
    """
    Display the number of cases for each
    business decision.
    """

    print()
    print("-" * 70)
    print("DECISION BREAKDOWN")
    print("-" * 70)

    decision_counts = (
        df["decision"]
        .value_counts()
    )

    for decision, count in decision_counts.items():

        percentage = (
            count / len(df)
        ) * 100

        print(
            f"{decision:<20} : "
            f"{count:>2} cases "
            f"({percentage:.1f}%)"
        )


# ============================================================
# ROOT CAUSE BREAKDOWN
# ============================================================

def print_root_cause_breakdown(df):
    """
    Display the number of cases
    belonging to each investigation category.
    """

    print()
    print("-" * 70)
    print("ROOT CAUSE BREAKDOWN")
    print("-" * 70)

    category_counts = (
        df["category"]
        .value_counts()
    )

    for category, count in category_counts.items():

        print(
            f"{category:<35} : {count:>2}"
        )


# ============================================================
# CASE TABLE
# ============================================================

def print_case_table(df):
    """
    Display a compact summary of every case.
    """

    print()
    print("-" * 70)
    print("CASE SUMMARY")
    print("-" * 70)

    print(
        f"{'Case ID':<16}"
        f"{'Type':<10}"
        f"{'Root Cause':<35}"
        f"{'Decision':<15}"
    )

    print("-" * 76)

    for _, row in df.iterrows():

        case_id = str(
            row["record_id"]
        )

        record_type = str(
            row["record_type"]
        )

        category = str(
            row["category"]
        )

        decision = str(
            row["decision"]
        )

        print(
            f"{case_id:<16}"
            f"{record_type:<10}"
            f"{category:<35}"
            f"{decision:<15}"
        )


# ============================================================
# CASE DETAILS
# ============================================================

def print_case_details(df):
    """
    Display detailed financial information
    for every investigation case.
    """

    print()
    print("=" * 70)
    print("DETAILED CASE ANALYSIS")
    print("=" * 70)

    for _, row in df.iterrows():

        print()
        print("-" * 70)

        print(
            f"CASE: {row['record_id']}"
        )

        print("-" * 70)

        print(
            f"Record Type        : "
            f"{row['record_type']}"
        )

        print(
            f"Root Cause         : "
            f"{row['category']}"
        )

        print(
            f"Decision            : "
            f"{row['decision']}"
        )

        print(
            f"Confidence          : "
            f"{float(row['confidence']):.0%}"
        )

        # ----------------------------------------------------
        # Invoice information
        # ----------------------------------------------------

        if pd.notna(row["invoice_id"]):

            print()
            print("Invoice")

            print(
                f"  ID                : "
                f"{row['invoice_id']}"
            )

            if pd.notna(row["invoice_customer"]):

                print(
                    f"  Customer          : "
                    f"{row['invoice_customer']}"
                )

            if pd.notna(row["invoice_amount"]):

                currency = (
                    row["invoice_currency"]
                    if pd.notna(
                        row["invoice_currency"]
                    )
                    else ""
                )

                print(
                    f"  Amount            : "
                    f"{float(row['invoice_amount']):,.2f} "
                    f"{currency}"
                )

            if pd.notna(row["invoice_date"]):

                print(
                    f"  Invoice Date      : "
                    f"{row['invoice_date']}"
                )

            if pd.notna(row["due_date"]):

                print(
                    f"  Due Date          : "
                    f"{row['due_date']}"
                )

        # ----------------------------------------------------
        # Payment information
        # ----------------------------------------------------

        if pd.notna(row["payment_id"]):

            print()
            print("Payment")

            print(
                f"  ID                : "
                f"{row['payment_id']}"
            )

            if pd.notna(row["payment_amount"]):

                currency = (
                    row["payment_currency"]
                    if pd.notna(
                        row["payment_currency"]
                    )
                    else ""
                )

                print(
                    f"  Amount            : "
                    f"{float(row['payment_amount']):,.2f} "
                    f"{currency}"
                )

            if pd.notna(row["payment_fee"]):

                print(
                    f"  Fee               : "
                    f"{float(row['payment_fee']):,.2f}"
                )

            if pd.notna(row["payment_date"]):

                print(
                    f"  Payment Date      : "
                    f"{row['payment_date']}"
                )

        # ----------------------------------------------------
        # Bank information
        # ----------------------------------------------------

        if pd.notna(row["bank_transaction_id"]):

            print()
            print("Bank Transaction")

            print(
                f"  ID                : "
                f"{row['bank_transaction_id']}"
            )

            if pd.notna(row["bank_amount"]):

                currency = (
                    row["bank_currency"]
                    if pd.notna(
                        row["bank_currency"]
                    )
                    else ""
                )

                print(
                    f"  Amount            : "
                    f"{float(row['bank_amount']):,.2f} "
                    f"{currency}"
                )

            if pd.notna(row["bank_deposit_date"]):

                print(
                    f"  Deposit Date      : "
                    f"{row['bank_deposit_date']}"
                )

        # ----------------------------------------------------
        # AI Investigation
        # ----------------------------------------------------

        print()
        print("AI Investigation")

        print(
            f"  Hypothesis        : "
            f"{row['hypothesis']}"
        )

        print(
            f"  Rationale         : "
            f"{row['rationale']}"
        )

        # ----------------------------------------------------
        # Business Decision
        # ----------------------------------------------------

        print()
        print("Business Decision")

        print(
            f"  Reason            : "
            f"{row['reason']}"
        )

        print(
            f"  Next Action       : "
            f"{row['next_action']}"
        )


# ============================================================
# MAIN
# ============================================================

def main():

    df = load_results()

    if df is None:
        return

    print_summary(df)

    print_decision_breakdown(df)

    print_root_cause_breakdown(df)

    print_case_table(df)

    print_case_details(df)

    print()
    print("=" * 70)
    print("REPORT GENERATION COMPLETED")
    print("=" * 70)


if __name__ == "__main__":
    main()